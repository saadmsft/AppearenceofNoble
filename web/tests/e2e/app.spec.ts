test('sources and methodology are reachable in both languages and research data downloads', async ({ page }) => {
  await page.goto('./?lang=en&view=sources')
  await expect(page.getByRole('heading', { name: 'Every description has a source.', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'What “comprehensive” does not mean here', exact: true })).toBeVisible()
  await page.locator('.source-index summary').first().click()
  await expect(page.locator('.source-index details[open] a').first()).toHaveAttribute('href', /^https:\/\/sunnah\.com\//)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'JSON', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('noble-appearance-research.json')
  const stream = await download.createReadStream()
  if (!stream) throw new Error('No research download stream')
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const data = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  expect(data.entries.length).toBeGreaterThanOrEqual(60)
  expect(data.entries.some((row: { grade: { level: string } }) => row.grade.level === 'weak')).toBe(true)
  await page.getByRole('link', { name: 'Reading guide', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Read with love. Read with context.', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'اردو', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('محبت سے پڑھیے')
})

