import { expect, test } from '@playwright/test'

test('English reading, Arabic source, keyboard dialog and focus restoration', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('./?lang=en&view=collection&scoutTheme=light')
  await expect(page.getByRole('heading', { name: 'Explore the collection', exact: true })).toBeVisible()
  const read = page.getByRole('button', { name: /^Read: / }).first()
  await read.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('Grading & attribution', { exact: true })).toBeVisible()
  await expect(dialog.locator('.reader-arabic [lang="ar"]')).toHaveAttribute('dir', 'rtl')
  await dialog.getByText('Read the full Arabic report', { exact: true }).click()
  await expect(dialog.locator('[data-full-arabic]')).toBeVisible()
  expect((await dialog.locator('[data-full-arabic]').textContent())?.length).toBeGreaterThan(100)
  await expect(dialog.getByRole('link', { name: 'Read the full source', exact: true })).toHaveAttribute('href', /^https:\/\/sunnah\.com\//)
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(read).toBeFocused()
  expect(errors).toEqual([])
})

