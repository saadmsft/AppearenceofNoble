test('no page overflow at small widths, with loaded local fonts and no depiction images', async ({ page }) => {
  for (const language of ['en', 'ur']) {
    await page.setViewportSize({ width: 360, height: 800 })
    await page.goto(`./?lang=${language}`)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(await page.locator('img').count()).toBe(0)
    expect(await page.evaluate(() => document.fonts.check('16px "Noto Naskh Arabic"'))).toBe(true)
    if (language === 'ur') expect(await page.evaluate(() => document.fonts.check('16px "Noto Nastaliq Urdu"'))).toBe(true)
  }
})

