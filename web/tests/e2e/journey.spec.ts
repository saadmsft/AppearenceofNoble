test('chapter motion stops when reading, offscreen, paused or system-reduced', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('./?lang=en')
  const complexion = page.locator('.journey-chapter[data-topic="complexion"]')
  const art = complexion.locator('.topic-artwork')
  await art.scrollIntoViewIfNeeded()
  await expect(art).toHaveAttribute('data-running', 'true')
  await complexion.getByRole('button', { name: 'View narrations about Complexion', exact: true }).click()
  await expect(art).toHaveAttribute('data-running', 'false')
  await complexion.getByRole('button', { name: 'Hide narrations about Complexion', exact: true }).click()
  await art.scrollIntoViewIfNeeded()
  await expect(art).toHaveAttribute('data-running', 'true')
  await complexion.getByRole('button', { name: 'Pause motion — Complexion', exact: true }).click()
  await expect(art).toHaveAttribute('data-running', 'false')
  await expect(art.locator('.topic-motion').first()).toHaveCSS('animation-name', 'none')
  await complexion.getByRole('button', { name: 'Resume motion — Complexion', exact: true }).click()
  await page.locator('.journey-chapter[data-topic="hair"] .topic-artwork').scrollIntoViewIfNeeded()
  await expect(art).toHaveAttribute('data-running', 'false')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.topic-artwork[data-running="true"]')).toHaveCount(0)
})

